# Kotlin rendering
# ---------------------------------------------------------------------------------------------------------------------
class KotlinFile:
    def __init__(self, package: str):
        self.package = package
        self.imports: set[str] = set()
        self.chunks: list[str] = []

    def use(self, fqcn: str):
        if fqcn.rsplit(".", 1)[0] != self.package:
            self.imports.add(fqcn)

    def render(self) -> str:
        def import_group(fqcn: str) -> int:
            if fqcn.startswith("java."):
                return 1
            if fqcn.startswith("javax."):
                return 2
            if fqcn.startswith("kotlin."):
                return 3
            return 0

        imports = sorted(self.imports, key=lambda i: (import_group(i), i))
        out = HEADER + "\n" + f"package {self.package}\n"
        if imports:
            out += "\n" + "".join(f"import {i}\n" for i in imports)
        out += "\n" + "\n".join(self.chunks)
        return out


def kdoc(text: str | None, indent: str) -> str:
    if not text:
        return ""
    text = text.replace("\r\n", "\n").replace("\r", "\n").replace("*/", "*&#47;").replace("/*", "&#47;*")
    lines = [line.rstrip() for line in text.strip().split("\n")]
    # collapse runs of blank lines
    cleaned: list[str] = []
    for line in lines:
        if not line and cleaned and not cleaned[-1]:
            continue
        cleaned.append(line)
    body = "".join(f"{indent} *{(' ' + line) if line else ''}\n" for line in cleaned)
    return f"{indent}/**\n{body}{indent} */\n"


class Renderer:
    def __init__(self, definitions: Definitions, actions: list[Action]):
        self.defs = definitions
        self.actions_by_name = {a.name: a for a in actions}

    # -- types --------------------------------------------------------------------------------------------------------
    def kotlin_type(self, prop: dict, file: KotlinFile) -> str:
        if "$ref" in prop:
            def_name = ref_name(prop["$ref"])
            if self.defs.is_custom_data(def_name):
                file.use(f"{BASE_PACKAGE}.common.CustomData")
                return "CustomData"
            package = self.defs.package(def_name, self.actions_by_name)
            class_name = self.defs.class_name(def_name)
            file.use(f"{package}.{class_name}")
            return class_name
        prop_type = prop.get("type")
        if prop_type is None:
            return "Any"
        if "enum" in prop:
            fail(f"inline enums are not supported: {prop}")
        if prop_type == "string":
            if prop.get("format") == "date-time":
                file.use("java.time.ZonedDateTime")
                return "ZonedDateTime"
            if "format" in prop:
                fail(f"unsupported string format {prop['format']}")
            return "String"
        if prop_type == "integer":
            return "Long"
        if prop_type == "number":
            file.use("java.math.BigDecimal")
            return "BigDecimal"
        if prop_type == "boolean":
            return "Boolean"
        if prop_type == "array":
            return f"List<{self.kotlin_type(prop['items'], file)}>"
        fail(f"unsupported property type {prop}")
        return ""

    def validations(self, kotlin_name: str, prop: dict, required: bool) -> list[str]:
        checks = []
        if prop.get("type") == "string" and "maxLength" in prop:
            limit = prop["maxLength"]
            checks.append(
                f"require({kotlin_name}.length <= {limit}) {{\n"
                f"    \"{kotlin_name.strip('`')} length > maximum {limit} - ${{{kotlin_name}.length}}\"\n"
                f"}}"
            )
        if prop.get("type") == "array" and ("minItems" in prop or "maxItems" in prop):
            low, high = prop.get("minItems"), prop.get("maxItems")
            if low is not None and high is not None:
                condition, text = f"{kotlin_name}.size in {low}..{high}", f"not in range {low}..{high}"
            elif low is not None:
                condition, text = f"{kotlin_name}.size >= {low}", f"< minimum {low}"
            else:
                condition, text = f"{kotlin_name}.size <= {high}", f"> maximum {high}"
            checks.append(
                f"require({condition}) {{\n"
                f"    \"{kotlin_name.strip('`')} size {text} - ${{{kotlin_name}.size}}\"\n"
                f"}}"
            )
        if required or not checks:
            return checks
        inner = "\n".join(checks)
        return [f"if ({kotlin_name} != null) {{\n" + indent_block(inner, "    ") + "\n}"]

    def data_class(self, name: str, schema: dict, file: KotlinFile, supertype: str | None) -> str:
        properties: dict = schema.get("properties", {})
        required = set(schema.get("required", []))
        ordered = [p for p in properties if p != "customData"] + (["customData"] if "customData" in properties else [])
        params = []
        checks = []
        for wire in ordered:
            prop = properties[wire]
            kotlin_name = kotlin_property_name(wire)
            kotlin_type = self.kotlin_type(prop, file)
            is_required = wire in required
            annotations = ""
            if needs_json_property(wire, kotlin_name):
                file.use("com.fasterxml.jackson.annotation.JsonProperty")
                annotations = (
                    f"    @param:JsonProperty(\"{wire}\")\n"
                    f"    @get:JsonProperty(\"{wire}\")\n"
                )
            declared_type = kotlin_type if is_required else f"{kotlin_type}? = null"
            if kotlin_type == "Any" and is_required:
                declared_type = "Any"
            params.append(kdoc(prop.get("description"), "    ") + annotations + f"    val {kotlin_name}: {declared_type}")
            checks.extend(self.validations(kotlin_name, prop, is_required))
        out = kdoc(schema.get("description"), "")
        inheritance = f" : {supertype}" if supertype else ""
        if not params:
            return out + f"class {name}{inheritance} {{\n    override fun equals(other: Any?): Boolean = other is {name}\n\n    override fun hashCode(): Int = {name}::class.hashCode()\n\n    override fun toString(): String = \"{name}()\"\n}}\n"
        out += f"data class {name}(\n" + ",\n".join(params) + f"\n){inheritance}"
        if checks:
            body = "\n".join(checks)
            out += " {\n    init {\n" + indent_block(body, "        ") + "\n    }\n}\n"
        else:
            out += "\n"
        return out

    def enum_class(self, name: str, definition: dict, file: KotlinFile) -> str:
        values = definition["enum"]
        constants = []
        for value in values:
            constant = enum_constant_name(value)
            if constant != value:
                file.use("com.fasterxml.jackson.annotation.JsonProperty")
                constants.append(f"    @JsonProperty(\"{value}\")\n    {constant}")
            else:
                constants.append(f"    {constant}")
        if len({enum_constant_name(v) for v in values}) != len(values):
            fail(f"enum constant collision in {name}")
        # ktlint requires an empty line before annotated declarations, so annotated enums get blank-line separated entries
        separator = ",\n\n" if any("@JsonProperty" in c for c in constants) else ",\n"
        return kdoc(definition.get("description"), "") + f"enum class {name} {{\n" + separator.join(constants) + "\n}\n"

    def definition(self, def_name: str, file: KotlinFile) -> str:
        definition = self.defs.by_name[def_name]
        class_name = self.defs.class_name(def_name)
        if self.defs.is_enum(def_name):
            return self.enum_class(class_name, definition, file)
        if definition.get("type") != "object":
            fail(f"unsupported definition {def_name}")
        return self.data_class(class_name, definition, file, None)


def indent_block(text: str, prefix: str) -> str:
    return "\n".join((prefix + line) if line else line for line in text.split("\n"))


