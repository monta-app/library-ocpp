        endpoint.use("com.monta.library.ocpp.client.OcppClient")
        endpoint.use("com.monta.library.ocpp.common.OcppClientConnectionEvent")
        endpoint.use("com.monta.library.ocpp.common.OcppClientDisconnectionEvent")
