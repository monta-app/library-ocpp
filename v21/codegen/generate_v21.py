def fail(message: str) -> None:
    print(f"ERROR: {message}", file=sys.stderr)
    sys.exit(1)


# ---------------------------------------------------------------------------------------------------------------------
# Naming helpers
# ---------------------------------------------------------------------------------------------------------------------
def kebab(action: str) -> str:
    s = re.sub(r"([a-zA-Z])([0-9])", r"\1-\2", action)
    s = re.sub(r"([0-9])([A-Za-z])", r"\1-\2", s)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1-\2", s)
    s = re.sub(r"([a-z])([A-Z])", r"\1-\2", s)
    return s.lower()


def kotlin_property_name(wire: str) -> str:
    parts = wire.split("_")
    name = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if not re.match(r"^[a-z][A-Za-z0-9]*$", name):
        fail(f"cannot derive a Kotlin property name from '{wire}'")
    return f"`{name}`" if name in KOTLIN_KEYWORDS else name


def needs_json_property(wire: str, kotlin_name: str) -> bool:
    # Explicit names whenever the Kotlin name differs, and for names Jackson's bean naming mangles
    # (second char upper case like ePriceLevel/vRef, or boolean-style "is" prefixes).
    return wire != kotlin_name.strip("`") or bool(re.match(r"^[a-z][A-Z]", wire)) or bool(re.match(r"^is[A-Z]", wire))


def enum_constant_name(value: str) -> str:
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", value) if p]
    name = "".join(p[:1].upper() + p[1:] for p in parts)
    if not name:
        fail(f"cannot derive an enum constant from '{value}'")
    if name[0].isdigit():
        name = "V" + name
    return name


