            "    onDisconnect: OcppClientDisconnectionEvent,\n"
            "    ocppSessionRepository: OcppSessionRepository,\n"
            "    settings: OcppSettings,\n"
            "    profiles: Set<ProfileDispatcher>,\n"
            "    sendHook: suspend (String, String) -> String?\n"
