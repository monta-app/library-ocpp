class SampleBuilder:
    def __init__(self, definitions: Definitions):
        self.defs = definitions

    def value(self, prop: dict, full: bool, depth: int):
        if depth > 12:
            fail("sample recursion too deep")
        if "$ref" in prop:
            def_name = ref_name(prop["$ref"])
            definition = self.defs.by_name[def_name]
            if self.defs.is_custom_data(def_name):
                return {"vendorId": "com.monta"}
            if "enum" in definition:
                values = definition["enum"]
                return values[-1] if full else values[0]
            return self.object(definition, full, depth + 1)
        prop_type = prop.get("type")
        if prop_type is None:
            return {"key": "value"}
        if prop_type == "string":
            if prop.get("format") == "date-time":
                return SAMPLE_DATE_TIME
            text = "Monta OCPP 2.1"
            return text[: prop.get("maxLength", len(text))]
        if prop_type == "integer":
            return int(clamp(7 if full else 1, prop))
        if prop_type == "number":
            return clamp(12.5 if full else 1.5, prop)
        if prop_type == "boolean":
            return full
        if prop_type == "array":
            count = max(1, prop.get("minItems", 1))
            return [self.value(prop["items"], full, depth + 1) for _ in range(count)]
        fail(f"cannot build sample for {prop}")
        return None

    def object(self, schema: dict, full: bool, depth: int = 0) -> dict:
        required = set(schema.get("required", []))
        result = {}
        for wire, prop in schema.get("properties", {}).items():
            if full or wire in required:
                result[wire] = self.value(prop, full, depth)
        return result


def clamp(value, prop):
    low, high = prop.get("minimum"), prop.get("maximum")
    if low is not None and value < low:
        value = low
    if high is not None and value > high:
        value = high
    return value


def write_samples(actions: list[Action], definitions: Definitions):
    try:
        from jsonschema import Draft6Validator
    except ImportError:
        fail("python package 'jsonschema' is required to validate the generated samples")
    builder = SampleBuilder(definitions)
    for kind in ("min", "max"):
        (SAMPLES_DIR / kind).mkdir(parents=True, exist_ok=True)
    for action in actions:
        messages = [(action.request_class, action.request_schema)]
        if action.response_schema is not None:
            messages.append((action.response_class, action.response_schema))
        for class_name, schema in messages:
            for kind in ("min", "max"):
                sample = builder.object(schema, full=(kind == "max"))
                errors = sorted(Draft6Validator(schema).iter_errors(sample), key=lambda e: list(e.path))
                if errors:
                    fail(f"generated {kind} sample for {class_name} is not schema-valid: {errors[0].message}")
                (SAMPLES_DIR / kind / f"{class_name}.json").write_text(
                    json.dumps(sample, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
                )


