def main():
    schemas = load_schemas()
    actions = build_actions(schemas)
    definitions = Definitions(actions)
    renderer = Renderer(definitions, actions)

    for generated_dir in (MAIN_DIR / "blocks", SAMPLES_DIR):
        if generated_dir.exists():
            shutil.rmtree(generated_dir)
    for path in (MAIN_DIR / "common").glob("*.kt") if (MAIN_DIR / "common").exists() else []:
        if path.read_text(encoding="utf-8").startswith(HEADER):
            path.unlink()

    for action in actions:
        target = MAIN_DIR / "blocks" / action.block / f"{action.name}.kt"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(generate_action_file(action, renderer, definitions), encoding="utf-8")

    common_dir = MAIN_DIR / "common"
    common_dir.mkdir(parents=True, exist_ok=True)
    common_count = 0
    for def_name in sorted(definitions.by_name):
        if definitions.is_custom_data(def_name) or definitions.owner_action(def_name) is not None:
            continue
        class_name = definitions.class_name(def_name)
        (common_dir / f"{class_name}.kt").write_text(generate_common_file(def_name, renderer, definitions), encoding="utf-8")
        common_count += 1

    (MAIN_DIR / "V21Actions.kt").write_text(generate_registry(actions), encoding="utf-8")
    write_samples(actions, definitions)

    counts = {d: sum(1 for a in actions if a.direction == d) for d in ("CSMS_TO_CS", "CS_TO_CSMS", "BOTH", "SEND")}
    print(
        f"generated {len(actions)} actions {counts}, {len(definitions.by_name)} definitions "
        f"({common_count} common), samples in {SAMPLES_DIR.relative_to(ROOT)}"
    )


if __name__ == "__main__":
    main()
