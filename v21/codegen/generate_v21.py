def generate_action_file(action: Action, renderer: Renderer, definitions: Definitions) -> str:
    file = KotlinFile(action.package)
    file.use("com.monta.library.ocpp.common.profile.Feature")
    file.use("com.monta.library.ocpp.common.profile.OcppConfirmation")
    file.use("com.monta.library.ocpp.common.profile.OcppRequest")
    request_supertype = "OcppUnconfirmedRequest" if action.direction == "SEND" else "OcppRequest"
    if action.direction == "SEND":
        file.use("com.monta.library.ocpp.common.profile.OcppUnconfirmedRequest")
        file.use("com.monta.library.ocpp.common.profile.NoConfirmation")
    confirmation = "NoConfirmation" if action.direction == "SEND" else f"{action.response_class}"
    feature = (
        kdoc(f"OCPP 2.1 {action.name} ({direction_text(action.direction)}).", "")
        + f"object {action.name}Feature : Feature {{\n"
        f"    override val name: String = \"{action.name}\"\n"
        f"    override val requestType: Class<out OcppRequest> = {action.request_class}::class.java\n"
        f"    override val confirmationType: Class<out OcppConfirmation> = {confirmation}::class.java\n"
        "}\n"
    )
    file.chunks.append(feature)
    file.chunks.append(renderer.data_class(action.request_class, action.request_schema, file, request_supertype))
    if action.response_schema is not None:
        file.chunks.append(renderer.data_class(action.response_class, action.response_schema, file, "OcppConfirmation"))
    local_defs = sorted(
        (d for d in definitions.by_name if definitions.owner_action(d) == action.name),
        key=lambda d: definitions.class_name(d),
    )
    for def_name in local_defs:
        file.chunks.append(renderer.definition(def_name, file))
    return file.render()


def direction_text(direction: str) -> str:
    return {
        "CS_TO_CSMS": "Charging Station to CSMS",
        "CSMS_TO_CS": "CSMS to Charging Station",
        "BOTH": "either direction",
        "SEND": "Charging Station to CSMS, unconfirmed SEND message",
    }[direction]


def generate_common_file(def_name: str, renderer: Renderer, definitions: Definitions) -> str:
    file = KotlinFile(f"{BASE_PACKAGE}.common")
    file.chunks.append(renderer.definition(def_name, file))
    return file.render()


def generate_registry(actions: list[Action]) -> str:
    file = KotlinFile(BASE_PACKAGE)
    file.use("com.monta.library.ocpp.common.profile.Feature")
    entries = []
    for action in sorted(actions, key=lambda a: a.name):
        file.use(f"{action.package}.{action.name}Feature")
        entries.append(
            f"        V21Action(\"{action.name}\", \"{kebab(action.name)}\", V21Direction.{action.direction}, "
            f"\"{action.block}\", {action.name}Feature)"
        )
    file.chunks.append(
        kdoc("Direction in which an OCPP 2.1 action is sent.", "")
        + "enum class V21Direction {\n"
        + "    /** Charging Station to CSMS (CALL). */\n    CS_TO_CSMS,\n\n"
        + "    /** CSMS to Charging Station (CALL). */\n    CSMS_TO_CS,\n\n"
        + "    /** Either direction (DataTransfer). */\n    BOTH,\n\n"
        + "    /** Unconfirmed SEND message (OCPP-J 2.1 message type 6), Charging Station to CSMS. */\n    SEND\n"
        + "}\n"
    )
    file.chunks.append(
        kdoc(
            "One OCPP 2.1 action.\n\n"
            "@property action the OCPP action name as used on the wire\n"
            "@property slug kebab-case name of the action, e.g. `get-15118-ev-certificate`\n"
            "@property direction who sends the request\n"
            "@property block the functional block (package) the action lives in\n"
            "@property feature the [Feature] describing the request/confirmation types",
            "",
        )
        + "data class V21Action(\n"
        "    val action: String,\n"
        "    val slug: String,\n"
        "    val direction: V21Direction,\n"
        "    val block: String,\n"
        "    val feature: Feature\n"
        ") {\n"
        "    /** True for actions a CSMS sends to a Charging Station. */\n"
        "    val sentByCsms: Boolean\n"
        "        get() = direction == V21Direction.CSMS_TO_CS || direction == V21Direction.BOTH\n\n"
        "    /** True for actions a Charging Station sends to a CSMS (including SEND). */\n"
        "    val sentByChargingStation: Boolean\n"
        "        get() = direction != V21Direction.CSMS_TO_CS\n"
        "}\n"
    )
    file.chunks.append(
        kdoc("Registry of all OCPP 2.1 actions.", "")
        + "object V21Actions {\n"
        "    val all: List<V21Action> = listOf(\n" + ",\n".join(entries) + "\n    )\n\n"
        "    /** All features, e.g. to look up a request type by action name. */\n"
        "    val features: List<Feature> = all.map { it.feature }\n\n"
        "    private val byAction = all.associateBy { it.action }\n"
        "    private val bySlug = all.associateBy { it.slug }\n"
        "    private val byRequestType = all.associateBy { it.feature.requestType }\n\n"
        "    fun byAction(action: String): V21Action? = byAction[action]\n\n"
        "    fun bySlug(slug: String): V21Action? = bySlug[slug]\n\n"
        "    fun byRequestType(requestType: Class<*>): V21Action? = byRequestType[requestType]\n"
        "}\n"
    )
    return file.render()


