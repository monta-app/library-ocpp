# Schema model
# ---------------------------------------------------------------------------------------------------------------------
def strip_descriptions(node):
    if isinstance(node, dict):
        return {k: strip_descriptions(v) for k, v in node.items() if k not in ("description", "comment")}
    if isinstance(node, list):
        return [strip_descriptions(v) for v in node]
    return node


@dataclass
class Action:
    name: str
    direction: str
    block: str
    request_schema: dict
    response_schema: dict | None

    @property
    def request_class(self) -> str:
        return f"{self.name}Request"

    @property
    def response_class(self) -> str | None:
        return f"{self.name}Response" if self.response_schema is not None else None

    @property
    def package(self) -> str:
        return f"{BASE_PACKAGE}.blocks.{self.block}"


def load_schemas() -> dict[str, dict]:
    schemas = {}
    for path in sorted(SCHEMA_DIR.glob("*.json")):
        schemas[path.stem] = json.loads(path.read_text(encoding="utf-8-sig"))
    if len(schemas) != 181:
        fail(f"expected 181 schema files in {SCHEMA_DIR}, found {len(schemas)}")
    return schemas


def build_actions(schemas: dict[str, dict]) -> list[Action]:
    actions = []
    seen_files = set()
    for name, direction, block in ACTIONS:
        if direction == "SEND":
            request_file, response_file = name, None
        else:
            request_file, response_file = f"{name}Request", f"{name}Response"
        if request_file not in schemas:
            fail(f"schema {request_file}.json missing")
        if response_file is not None and response_file not in schemas:
            fail(f"schema {response_file}.json missing")
        seen_files.add(request_file)
        if response_file:
            seen_files.add(response_file)
        actions.append(
            Action(
                name=name,
                direction=direction,
                block=block,
                request_schema=schemas[request_file],
                response_schema=schemas[response_file] if response_file else None,
            )
        )
    unused = set(schemas) - seen_files
    if unused:
        fail(f"schemas not covered by the action table: {sorted(unused)}")
    if len({a.name for a in actions}) != len(actions):
        fail("duplicate action in action table")
    return actions


class Definitions:
    """All `definitions` across the schemas, de-duplicated by name and checked for structural equality."""

    def __init__(self, actions: list[Action]):
        self.by_name: dict[str, dict] = {}
        self.stripped: dict[str, dict] = {}
        self.used_by: dict[str, set[str]] = {}
        for action in actions:
            for schema in (action.request_schema, action.response_schema):
                if schema is None:
                    continue
                for def_name, definition in schema.get("definitions", {}).items():
                    stripped = strip_descriptions(definition)
                    if def_name in self.stripped and self.stripped[def_name] != stripped:
                        fail(f"definition {def_name} differs structurally between schemas")
                    self.by_name.setdefault(def_name, definition)
                    self.stripped.setdefault(def_name, stripped)
                    self.used_by.setdefault(def_name, set()).add(action.name)
        self.class_names = {name: d["javaType"] for name, d in self.by_name.items()}
        if len(set(self.class_names.values())) != len(self.class_names):
            fail("duplicate javaType names")

    def is_custom_data(self, def_name: str) -> bool:
        return def_name == "CustomDataType"

    def is_enum(self, def_name: str) -> bool:
        return "enum" in self.by_name[def_name]

    def class_name(self, def_name: str) -> str:
        return self.class_names[def_name]

    def package(self, def_name: str, actions_by_name: dict[str, Action]) -> str:
        if self.is_custom_data(def_name):
            return f"{BASE_PACKAGE}.common"
        users = self.used_by[def_name]
        if len(users) == 1:
            return actions_by_name[next(iter(users))].package
        return f"{BASE_PACKAGE}.common"

    def owner_action(self, def_name: str) -> str | None:
        users = self.used_by[def_name]
        if self.is_custom_data(def_name) or len(users) != 1:
            return None
        return next(iter(users))


def ref_name(ref: str) -> str:
    prefix = "#/definitions/"
    if not ref.startswith(prefix):
        fail(f"unsupported $ref {ref}")
    return ref[len(prefix):]


