package com.monta.library.ocpp.v21

import com.monta.library.ocpp.common.serialization.Message
import com.monta.library.ocpp.common.serialization.MessageSerializer
import com.monta.library.ocpp.common.serialization.ParsingResult
import com.monta.library.ocpp.common.serialization.SerializationMode
import com.monta.library.ocpp.v21.error.OcppErrorResponderV21
import io.kotest.core.spec.style.FunSpec
import io.kotest.matchers.shouldBe
import io.kotest.matchers.types.shouldBeInstanceOf
import tools.jackson.databind.json.JsonMapper

/**
 * Every OCPP 2.1 request/response class must read and write its official JSON schema faithfully.
 *
 * The samples in `samples/{min,max}` are generated by `v21/codegen/generate_v21.py` and validated against the official
 * OCA schemas at generation time: `min` holds only required fields, `max` holds every field. Deserializing a sample and
 * serializing it again must give back exactly the same JSON.
 */
class SchemaRoundTripTest : FunSpec({

    val serializer = MessageSerializer(SerializationMode.OCPP_2_1, OcppErrorResponderV21)
    val treeMapper = JsonMapper.builder().build()

    fun sample(kind: String, className: String): String {
        val path = "/samples/$kind/$className.json"
        return requireNotNull(SchemaRoundTripTest::class.java.getResource(path)) { "missing sample $path" }.readText()
    }

    fun roundTrip(kind: String, type: Class<*>) {
        val json = sample(kind, type.simpleName)
        val frame = serializer.parse("[2,\"sample\",\"Sample\",$json]")
        frame.shouldBeInstanceOf<ParsingResult.Success<Message>>()
        val message = frame.value as Message.Request

        val parsed = serializer.deserializePayload(message, type)
        if (parsed is ParsingResult.Failure) {
            throw AssertionError("could not deserialize $kind sample of ${type.simpleName}", parsed.throwable)
        }
        parsed.shouldBeInstanceOf<ParsingResult.Success<Any>>()

        val written = serializer.serializePayload(serializer.toPayload(parsed.value))
        treeMapper.readTree(written) shouldBe treeMapper.readTree(json)
    }

    V21Actions.all.forEach { action ->
        listOf("min", "max").forEach { kind ->
            test("$kind ${action.feature.requestType.simpleName}") {
                roundTrip(kind, action.feature.requestType)
            }
            if (action.direction != V21Direction.SEND) {
                test("$kind ${action.feature.confirmationType.simpleName}") {
                    roundTrip(kind, action.feature.confirmationType)
                }
            }
        }
    }
})
